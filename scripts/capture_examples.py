#!/usr/bin/env python
"""Run the example queries through ``scripts/query.py`` and save their real output.

    python scripts/capture_examples.py

Writes ``out/store/example_queries.md``. The file is generated, never hand-edited,
so every number in it is reproducible with ``make store``.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

EXAMPLES: list[tuple[str, list[str]]] = [
    ("Per-class manifest counts", ["--counts"]),
    ("Construction-zone frames above 0.6 confidence", ["--tag", "construction_zone", "--min-conf", "0.6", "--limit", "8"]),
    ("Occluded pedestrians above 0.8 confidence", ["--tag", "occluded_pedestrian", "--min-conf", "0.8", "--limit", "5"]),
    ("Manifest vs ground truth", ["--agreement"]),
    ("Frames carrying the most tags", ["--frames", "--limit", "5"]),
    (
        "Raw SQL: detections per location and class",
        ["--sql", "SELECT location, class_name, COUNT(*) AS detections FROM scenarios GROUP BY 1, 2 ORDER BY 1, 2"],
    ),
    (
        "Raw SQL: highest-confidence detection per class",
        [
            "--sql",
            "SELECT class_name, frame_id, ROUND(MAX(confidence), 3) AS best_confidence "
            "FROM scenarios GROUP BY 1, 2 QUALIFY ROW_NUMBER() OVER "
            "(PARTITION BY class_name ORDER BY best_confidence DESC, frame_id) = 1 ORDER BY class_name",
        ],
    ),
]


def run_query(argv: list[str]) -> str:
    completed = subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / "query.py"), *argv],
        capture_output=True,
        text=True,
        check=False,
    )
    output = completed.stdout.rstrip("\n")
    if completed.returncode != 0:
        output += f"\n[exit {completed.returncode}]\n{completed.stderr.rstrip()}"
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "out" / "store" / "example_queries.md")
    parser.add_argument("--python", default=sys.executable)
    args = parser.parse_args(argv)

    blocks: list[str] = []
    blocks.append("# Example scenario-manifest queries\n")
    blocks.append(
        "Every block below is the verbatim stdout of a real run of `scripts/query.py` "
        "against the checked-in manifest in `out/store/scenarios/`, regenerated by "
        "`make store`.\n"
    )
    for title, query_args in EXAMPLES:
        command = "python scripts/query.py " + " ".join(query_args)
        output = run_query(query_args)
        blocks.append(f"## {title}\n")
        blocks.append(f"```console\n$ {command}\n{output}\n```\n")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(blocks), encoding="utf-8")
    print(f"wrote {args.out} ({len(EXAMPLES)} queries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
